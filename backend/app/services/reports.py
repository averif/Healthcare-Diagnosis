"""PDF report for a prediction, built with ReportLab (pure Python, works on Windows)."""

from __future__ import annotations

from datetime import UTC, datetime
from pathlib import Path
from xml.sax.saxutils import escape

from reportlab.graphics.barcode.qr import QrCodeWidget
from reportlab.graphics.shapes import Drawing
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import (
    KeepTogether,
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)

from ..models import Prediction, Report

BRAND = colors.HexColor("#0d8574")
LIGHT = colors.HexColor("#effcfa")
GREY = colors.HexColor("#64748b")
RISK_COLOURS = {
    "low": colors.HexColor("#16a34a"),
    "moderate": colors.HexColor("#d97706"),
    "high": colors.HexColor("#dc2626"),
}
DISEASE_TITLES = {
    "diabetes": "Diabetes risk assessment",
    "heart": "Heart disease risk assessment",
    "liver": "Liver disease risk assessment",
    "symptom": "Symptom-based condition assessment",
}
DISCLAIMER = (
    "This report was generated by an AI clinical decision support prototype for preliminary "
    "assessment and education only. It is NOT a medical diagnosis and must be interpreted by a "
    "qualified healthcare professional together with the full clinical picture."
)

_styles = getSampleStyleSheet()
H1 = ParagraphStyle(
    "H1", parent=_styles["Title"], textColor=BRAND, fontSize=18, spaceAfter=2, alignment=0
)
H2 = ParagraphStyle(
    "H2", parent=_styles["Heading2"], textColor=BRAND, fontSize=12, spaceBefore=10, spaceAfter=4
)
BODY = ParagraphStyle("Body", parent=_styles["BodyText"], fontSize=9.5, leading=13)
SMALL = ParagraphStyle("Small", parent=BODY, fontSize=8, leading=10, textColor=GREY)


#: Characters outside the built-in PDF fonts (WinAnsi), replaced so they don't render as boxes
_SAFE = str.maketrans({"≥": ">=", "≤": "<=", "−": "-", "⚠": "!", "→": "->"})


def _p(text: object, style: ParagraphStyle = BODY) -> Paragraph:
    return Paragraph(escape(str(text).translate(_SAFE)), style)


def _table(rows: list[list], widths: list[float], header: bool = True) -> Table:
    table = Table(rows, colWidths=widths, hAlign="LEFT")
    style = [
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#cbd5e1")),
        ("TOPPADDING", (0, 0), (-1, -1), 3),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
    ]
    if header:
        style += [
            ("BACKGROUND", (0, 0), (-1, 0), LIGHT),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ]
    table.setStyle(TableStyle(style))
    return table


def _qr(text: str, size: float = 24 * mm) -> Drawing:
    widget = QrCodeWidget(text)
    x1, y1, x2, y2 = widget.getBounds()
    drawing = Drawing(size, size, transform=[size / (x2 - x1), 0, 0, size / (y2 - y1), 0, 0])
    drawing.add(widget)
    return drawing


def _input_rows(prediction: Prediction, feature_specs: list[dict]) -> list[list]:
    rows: list[list] = [["Parameter", "Value"]]
    if prediction.disease.value == "symptom":
        symptoms = prediction.input_data.get("symptoms", [])
        rows.append(["Reported symptoms", _p(", ".join(s.replace("_", " ") for s in symptoms))])
        return rows
    for spec in feature_specs:
        value = prediction.input_data.get(spec["name"])
        if value is None:
            shown = "not provided"
        elif spec["choices"]:
            code = str(int(value)) if float(value).is_integer() else str(value)
            shown = spec["choices"].get(code, str(value))
        else:
            shown = (
                f"{value:g} {spec['unit']}".strip()
                if isinstance(value, float)
                else f"{value} {spec['unit']}".strip()
            )
        rows.append([_p(spec["label"]), shown])
    return rows


def build_pdf(
    prediction: Prediction, report: Report, path: Path, feature_specs: list[dict]
) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    patient = prediction.patient
    risk = prediction.risk_level.value
    generated = datetime.now(UTC).strftime("%d %b %Y, %H:%M UTC")

    doc = SimpleDocTemplate(
        str(path),
        pagesize=A4,
        leftMargin=18 * mm,
        rightMargin=18 * mm,
        topMargin=15 * mm,
        bottomMargin=15 * mm,
        title=f"MediAssist report {report.report_code}",
        author="MediAssist CDSS",
    )
    story: list = []

    header = Table(
        [
            [
                [
                    _p("MediAssist CDSS", H1),
                    _p(DISEASE_TITLES[prediction.disease.value], H2),
                    _p(f"Report {report.report_code}  ·  Generated {generated}", SMALL),
                ],
                _qr(f"MediAssist report {report.report_code}"),
            ]
        ],
        colWidths=[140 * mm, 34 * mm],
    )
    header.setStyle(
        TableStyle([("VALIGN", (0, 0), (-1, -1), "TOP"), ("ALIGN", (1, 0), (1, 0), "RIGHT")])
    )
    story += [header, Spacer(1, 4)]

    story.append(_p("Patient", H2))
    story.append(
        _table(
            [
                ["Name", patient.user.full_name, "Patient ID", f"P-{patient.id:05d}"],
                [
                    "Age",
                    patient.age if patient.age is not None else "—",
                    "Sex",
                    patient.sex.value if patient.sex else "—",
                ],
                [
                    "Assessment date",
                    prediction.created_at.strftime("%d %b %Y"),
                    "Requested by",
                    prediction.created_by.full_name if prediction.created_by else "—",
                ],
            ],
            [30 * mm, 57 * mm, 30 * mm, 57 * mm],
            header=False,
        )
    )

    story.append(_p("Result", H2))
    result_rows = [
        ["Prediction", prediction.predicted_label],
        ["Probability", f"{prediction.probability:.0%}"],
        ["Risk level", risk.upper()],
    ]
    top = prediction.explanation.get("top_conditions")
    if top:
        result_rows.append(
            [
                "Other possibilities",
                ", ".join(f"{c['condition']} ({c['probability']:.0%})" for c in top[1:]) or "—",
            ]
        )
    result_table = _table(result_rows, [45 * mm, 129 * mm], header=False)
    result_table.setStyle(
        TableStyle(
            [
                ("TEXTCOLOR", (1, 2), (1, 2), RISK_COLOURS[risk]),
                ("FONTNAME", (1, 0), (1, 2), "Helvetica-Bold"),
            ]
        )
    )
    story.append(result_table)

    flags = prediction.explanation.get("red_flags") or []
    if flags:
        story.append(_p("Warnings", H2))
        for flag in flags:
            story.append(
                _p(f"! {flag}", ParagraphStyle("Flag", parent=BODY, textColor=RISK_COLOURS["high"]))
            )

    explanation = prediction.explanation.get("explanation") or {}
    reasons = [r for r in explanation.get("reasons", []) if abs(r["contribution"]) >= 0.005][:8]
    if reasons:
        story.append(_p("Why the model reached this result", H2))
        story.append(
            _p(
                "Each factor shows how much it raised (+) or lowered (-) the predicted "
                f"probability, starting from a baseline of {explanation.get('base_rate', 0):.0%}.",
                SMALL,
            )
        )
        rows = [["Factor", "Effect"]] + [
            [_p(r["text"]), f"{r['contribution'] * 100:+.1f} pts"] for r in reasons
        ]
        story.append(_table(rows, [144 * mm, 30 * mm]))

    story.append(
        KeepTogether(
            [
                _p("Information provided", H2),
                _table(_input_rows(prediction, feature_specs), [80 * mm, 94 * mm]),
            ]
        )
    )

    story.append(_p("General guidance", H2))
    for item in prediction.explanation.get("guidance", []):
        story.append(_p(f"• {item}"))

    story.append(_p("Clinician review", H2))
    review = prediction.review
    if review:
        doctor = review.doctor.full_name if review.doctor else "Doctor"
        story.append(
            _p(f"{doctor} — verdict: {review.verdict.value.upper()} ({review.created_at:%d %b %Y})")
        )
        if review.notes:
            story.append(_p(f"Notes: {review.notes}"))
    else:
        story.append(_p("Pending review by a doctor.", SMALL))

    mv = prediction.model_version
    if mv:
        test = mv.metrics.get("test", {})
        metric_text = ", ".join(
            f"{k.replace('_', ' ')} {test[k]:.2f}"
            for k in ("accuracy", "recall", "roc_auc")
            if k in test
        )
        story.append(Spacer(1, 6))
        story.append(
            _p(f"Model: {mv.algorithm} v{mv.version} · hold-out test {metric_text}", SMALL)
        )

    story += [
        Spacer(1, 8),
        _p(
            DISCLAIMER,
            ParagraphStyle(
                "Disc",
                parent=SMALL,
                borderColor=colors.HexColor("#fcd34d"),
                borderWidth=0.5,
                borderPadding=5,
                backColor=colors.HexColor("#fffbeb"),
                textColor=colors.HexColor("#78350f"),
            ),
        ),
    ]

    doc.build(story)
    return path
